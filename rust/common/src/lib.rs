// ── Tests ───────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_resource_bounds_creation() {
        let rb = ResourceBounds::new(0.5, 1_000_000.0, 100.0, 0.01);
        assert_eq!(rb.b_time, 0.5);
        assert!(rb.b_mem > 0.0);
    }

    #[test]
    fn test_state_vector_creation() {
        let sv = StateVector::new(
            vec![0.1, 0.2, 0.3],
            vec![1.0, 0.8, 0.5],
            42.0,
            1,
        );
        assert_eq!(sv.dim(), 3);
        assert_eq!(sv.grounding_level, 1);
    }

    #[test]
    fn test_goal_vector_creation() {
        let gv = GoalVector::new(1, vec![0.5, 0.5], 0.1, 0, 0.8);
        assert_eq!(gv.drive_id, 1);
        assert_eq!(gv.target_values.len(), 2);
    }

    #[test]
    fn test_serialization_roundtrip() {
        let rb = ResourceBounds::new(0.5, 1_000_000.0, 100.0, 0.01);
        let json = serde_json::to_string(&rb).unwrap();
        let rb2: ResourceBounds = serde_json::from_str(&json).unwrap();
        assert_eq!(rb.b_time, rb2.b_time);
    }
}
